		migration_errors[#migration_errors + 1] = "hyprland/colors.conf:29: hyprbars is not loaded; button pending."
	end
	for name in pairs(loaded) do
		plugins_configured[name] = true
	end
end

-- Completion report: inspect this as well as `hyprctl configerrors`.
local function write_report()
	local lines = {
		"Hyprland consolidated migration: runtime registration report",
		"This is not proof that every application or IPC endpoint works.",
		"Preserved old ii-only shortcuts require that shell or a deliberate Caelestia replacement.",
		"Scripts can themselves contain old Hyprland dispatch commands; their source was not uploaded.",
		"",
	}
	for _, message in ipairs(migration_errors) do
		lines[#lines + 1] = message
	end
	lines[#lines + 1] = ""
	lines[#lines + 1] = "Referenced helper scripts (existence only; contents/runtime not checked):"
	for _, path in ipairs({
		"~/.config/hypr/custom/scripts/__restore_video_wallpaper.sh",
		"~/.config/hypr/hyprland/scripts/ai/primary-buffer-query.sh",
		"~/.config/hypr/hyprland/scripts/keybinds_cheatsheet.sh",
		"~/.config/hypr/hyprland/scripts/launch_first_available.sh",
		"~/.config/hypr/hyprland/scripts/snip_to_search.sh",
		"~/.config/hypr/hyprland/scripts/start_geoclue_agent.sh",
		"~/.config/hypr/hyprland/scripts/wallpaper_picker.sh",
		"~/.config/hypr/hyprland/scripts/workspace_action.sh",
		"~/.config/hypr/hyprland/scripts/zoom.sh",
	}) do
		local full_path = path:gsub("^~", HOME)
		local f = io.open(full_path, "r")
		lines[#lines + 1] = (f and "FOUND   " or "MISSING ") .. full_path
		if f then
			f:close()
		end
	end
	local f = io.open(report_path, "w")
	if f then
		f:write(table.concat(lines, "\n") .. "\n")
		f:close()
	end
	if #migration_errors > 0 then
		pcall(function()
			hl.notification.create({
				text = "Migration: " .. #migration_errors .. " items need attention. Read " .. report_path,
				timeout = 12000,
				icon = 1,
			})
		end)
	end
end

configure_plugins()
write_report()

hl.on("hyprland.start", function()
	-- Restores all original exec-once commands in original order.
	-- Do not invoke the startup list on config reload: that would duplicate daemons.
	for _, command in ipairs(startup_commands) do
		hl.exec_cmd("bash -c " .. shell_quote(command))
	end
	-- The initial `hyprpm reload` is asynchronous; retry plugin configuration afterwards.
	hl.timer(function()
		configure_plugins()
		write_report()
	end, { timeout = 2500, type = "oneshot" })
end)

