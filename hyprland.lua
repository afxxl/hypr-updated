local migration_errors = {}
local function attempt(label, fn)
	local ok, result = pcall(fn)
	if not ok then
		migration_errors[#migration_errors + 1] = label .. ": " .. tostring(result)
	elseif type(result) == "table" and result.ok == false then
		migration_errors[#migration_errors + 1] = label
			.. ": "
			.. tostring(result.error or result.message or "rejected")
	end
	return ok, result
end
local function setting(key, val, source)
	attempt(source .. " / " .. key, function()
		hl.config({ [key] = val })
	end)
end
